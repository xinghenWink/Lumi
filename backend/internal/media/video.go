type AVFile struct {
	Params   query.InsertImageFileParams
	Duration int64
}

type streamInfo struct {
	CodecType string `json:"codec_type"`
	CodecName string `json:"codec_name"`
	Width     int32
	Height    int32
}

type avMetadata struct {
	Streams []streamInfo
	Format  struct {
		Duration   string
		FormatName string `json:"format_name"`
	}
}

func probe(ctx context.Context, path string) (avMetadata, error) {
	var result avMetadata
	ctx, cancel := context.WithTimeout(ctx, 20*time.Second)
	defer cancel()
	// The input is a server-created local file. Restrict nested media references.
	command := exec.CommandContext(ctx, "ffprobe", "-v", "error", "-protocol_whitelist", "file", "-format_whitelist", "mov,mp4,m4a,3gp,3g2,mj2,mp3,wav", "-show_entries", "stream=codec_type,codec_name,width,height:format=duration,format_name", "-of", "json", path) // #nosec G204 -- The path is generated by Lumi within the media root and passed directly to the executable.
	data, err := command.Output()
	if err != nil {
		return result, fmt.Errorf("probe audio/video: %w", err)
	}
	if err := json.Unmarshal(data, &result); err != nil {
		return result, fmt.Errorf("decode audio/video metadata: %w", err)
	}
	return result, nil
}

func (s *Store) PrepareAV(ctx context.Context, owner uuid.UUID, task *uuid.UUID, input io.Reader, kind string, limit int64, stripAudio bool) (result AVFile, resultErr error) {
	select {
	case s.decodeSlots <- struct{}{}:
		defer func() { <-s.decodeSlots }()
	case <-ctx.Done():
		return AVFile{}, fmt.Errorf("wait for media preparation: %w", ctx.Err())
	}
	id, err := validation.NewID()
	if err != nil {
		return AVFile{}, err
	}
	dir := owner.String()
	if err := s.root.MkdirAll(dir, 0700); err != nil {
		return AVFile{}, fmt.Errorf("create media directory: %w", err)
	}
	stage := dir + "/" + id.String() + ".tmp"
	file, err := s.root.OpenFile(stage, os.O_CREATE|os.O_EXCL|os.O_WRONLY, 0600)
	if err != nil {
		return AVFile{}, fmt.Errorf("stage media: %w", err)
	}
	defer func() {
		if err := s.remove(stage); err != nil {
			resultErr = errors.Join(resultErr, err)
		}
	}()
	size, writeErr := io.Copy(file, io.LimitReader(input, limit+1))
	if err := errors.Join(writeErr, file.Close()); err != nil {
		return AVFile{}, fmt.Errorf("copy media: %w", err)
	}
	if size < 1 || size > limit {
		return AVFile{}, problem.New("FILE_TOO_LARGE", 413)
	}
	filename := filepath.Join(s.root.Name(), filepath.FromSlash(stage))
	info, err := probe(ctx, filename)
	if err != nil {
		return AVFile{}, problem.New("VIDEO_MEDIA_INVALID", 400)
	}
	duration, err := strconv.ParseFloat(info.Format.Duration, 64)
	if err != nil || !(duration > 0 && duration <= 3600) {
		return AVFile{}, problem.New("VIDEO_MEDIA_INVALID", 400)
	}
	var width, height int32
	var audio bool
	for _, stream := range info.Streams {
		if stream.CodecType == "video" && (stream.CodecName == "h264" || stream.CodecName == "hevc") {
			width, height = stream.Width, stream.Height
		}
		audio = audio || stream.CodecType == "audio"
	}
	mime, ext := "video/mp4", ".mp4"
	if kind == "audio_upload" {
		if !audio || width != 0 {
			return AVFile{}, problem.New("VIDEO_MEDIA_INVALID", 400)
		}
		switch info.Format.FormatName {
		case "mp3":
			mime, ext = "audio/mpeg", ".mp3"
		case "wav":
			mime, ext = "audio/wav", ".wav"
		default:
			return AVFile{}, problem.New("VIDEO_MEDIA_INVALID", 400)
		}
		width, height = 1, 1
	} else if width < 1 || width > 8192 || height < 1 || height > 8192 || !strings.Contains(info.Format.FormatName, "mp4") {
		return AVFile{}, problem.New("VIDEO_MEDIA_INVALID", 400)
	}
	published := stage
	if stripAudio && audio {
		silent := dir + "/" + id.String() + "-silent.tmp"
		defer func() {
			if err := s.remove(silent); err != nil {
				resultErr = errors.Join(resultErr, err)
			}
		}()
		target := filepath.Join(s.root.Name(), filepath.FromSlash(silent))
		remuxCtx, cancel := context.WithTimeout(ctx, 90*time.Second)
		defer cancel()
		command := exec.CommandContext(remuxCtx, "ffmpeg", "-nostdin", "-loglevel", "error", "-n", "-protocol_whitelist", "file", "-f", "mov", "-i", filename, "-map", "0:v:0", "-c:v", "copy", "-an", "-movflags", "+faststart", "-f", "mp4", target) // #nosec G204 -- Source and destination are server-generated local paths; FFmpeg uses no shell.
		if err := command.Run(); err != nil {
			return AVFile{}, fmt.Errorf("remove video audio: %w", err)
		}
		published = silent
	}
	src, err := s.root.Open(published)
	if err != nil {
		return AVFile{}, fmt.Errorf("open staged media: %w", err)
	}
	digest := sha256.New()
	n, readErr := io.Copy(digest, io.LimitReader(src, limit+1))
	if err := errors.Join(readErr, src.Close()); err != nil {
		return AVFile{}, fmt.Errorf("hash staged media: %w", err)
	}
	if n < 1 || n > limit {
		return AVFile{}, problem.New("FILE_TOO_LARGE", 413)
	}
	path := dir + "/" + id.String() + ext
	if err := s.root.Rename(published, path); err != nil {
		return AVFile{}, fmt.Errorf("publish media: %w", err)
	}
	return AVFile{Duration: int64(duration * 1000), Params: query.InsertImageFileParams{ID: id, UserID: owner, TaskID: task, Kind: kind, Path: path, ThumbnailPath: path, Mime: mime, Size: n, Width: width, Height: height, ThumbnailWidth: 1, ThumbnailHeight: 1, Sha256: hex.EncodeToString(digest.Sum(nil))}}, nil
}

func (s *Store) VideoTicket(file, scope uuid.UUID, kind string, expires int64) string {
	return s.signed(file, scope, "video:"+kind, expires)
}

func (s *Store) VerifyVideoTicket(file, scope uuid.UUID, kind string, expires int64, signature string) bool {
	now := time.Now().Unix()
	return expires >= now && expires <= now+7200 && len(signature) > 0 && hmac.Equal([]byte(signature), []byte(s.VideoTicket(file, scope, kind, expires)))
}
